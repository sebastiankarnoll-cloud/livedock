#!/usr/bin/env bash
# Local development database. Creates roles, the dev and test databases, migrates them,
# and writes .env with freshly generated passwords (no default passwords, nothing in git).
set -euo pipefail
cd "$(dirname "$0")/.."
# Linux (root): act as the postgres user. macOS (Homebrew): your own user is the database superuser.
SU() { if [ "$(id -u)" = 0 ] && id postgres >/dev/null 2>&1; then su postgres -c "$1"; else bash -c "$1"; fi; }
H="localhost:5432"

if [ ! -f .env ] || ! grep -q '^DATABASE_URL=' .env; then
  OWNER_PW=$(openssl rand -hex 16); APP_PW=$(openssl rand -hex 16); WORKER_PW=$(openssl rand -hex 16)
  cat > .env <<ENV
# Generated by scripts/dev-db.sh. Not in git.
DATABASE_URL=postgres://livedock_app:${APP_PW}@${H}/livedock_dev
DATABASE_ADMIN_URL=postgres://livedock_owner:${OWNER_PW}@${H}/livedock_dev
DATABASE_WORKER_URL=postgres://livedock_worker:${WORKER_PW}@${H}/livedock_dev
TEST_DATABASE_URL=postgres://livedock_app:${APP_PW}@${H}/livedock_test
TEST_DATABASE_ADMIN_URL=postgres://livedock_owner:${OWNER_PW}@${H}/livedock_test
TEST_DATABASE_WORKER_URL=postgres://livedock_worker:${WORKER_PW}@${H}/livedock_test
MAILER=dev
DEV_OUTBOX=1
PUBLIC_URL=http://localhost:3000
STORAGE_DIR=./storage
ENV
  chmod 600 .env
fi
# Control center role (added later than the first three): generate once if missing.
if ! grep -q '^DATABASE_STAFF_URL=' .env; then
  STAFF_PW=$(openssl rand -hex 16)
  cat >> .env <<ENV
DATABASE_STAFF_URL=postgres://livedock_staff:${STAFF_PW}@${H}/livedock_dev
TEST_DATABASE_STAFF_URL=postgres://livedock_staff:${STAFF_PW}@${H}/livedock_test
STAFF_EMAILS=staff@livedock.test
ENV
fi
# Password part of a URL line in .env: value between the second colon and the at sign.
pw() { local v; v=$(grep "^$1=" .env | head -1 | cut -d= -f2-); v=${v#*://}; v=${v#*:}; echo "${v%%@*}"; }
OWNER_PW=$(pw DATABASE_ADMIN_URL); APP_PW=$(pw DATABASE_URL); WORKER_PW=$(pw DATABASE_WORKER_URL); STAFF_PW=$(pw DATABASE_STAFF_URL)

SU "psql -v ON_ERROR_STOP=1 -q" <<SQL
do \$\$ begin
  if not exists (select from pg_roles where rolname = 'livedock_owner') then create role livedock_owner login createdb; end if;
  if not exists (select from pg_roles where rolname = 'livedock_worker') then create role livedock_worker login nosuperuser bypassrls; end if;
  if not exists (select from pg_roles where rolname = 'livedock_staff') then create role livedock_staff login nosuperuser bypassrls; end if;
  if not exists (select from pg_roles where rolname = 'livedock_app') then create role livedock_app login nosuperuser nobypassrls; end if;
end \$\$;
alter role livedock_owner password '${OWNER_PW}';
alter role livedock_app password '${APP_PW}';
alter role livedock_worker password '${WORKER_PW}';
alter role livedock_staff password '${STAFF_PW}';
SQL
for db in livedock_dev livedock_test; do
  SU "psql -tAc \"select 1 from pg_database where datname='$db'\"" | grep -q 1 || \
    SU "psql -c \"create database $db owner livedock_owner\""
  SU "psql -d $db -q -c 'create extension if not exists citext; create extension if not exists pgcrypto;'" 2>/dev/null
  key=DATABASE_ADMIN_URL; [ "$db" = livedock_test ] && key=TEST_DATABASE_ADMIN_URL
  DATABASE_ADMIN_URL=$(grep "^$key=" .env | cut -d= -f2-) node scripts/migrate.ts
done
echo "ok: livedock_dev and livedock_test ready"
